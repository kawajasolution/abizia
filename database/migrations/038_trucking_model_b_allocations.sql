CREATE TABLE exp_manifest_allocations (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 dn_id INT UNSIGNED NOT NULL,
 source_manifest_id INT UNSIGNED NULL,
 target_manifest_id INT UNSIGNED NOT NULL,
 quantity DECIMAL(12,3) NOT NULL,
 unit VARCHAR(30) NOT NULL,
 source_branch_id INT UNSIGNED NOT NULL,
 source_location_id INT UNSIGNED NULL,
 target_branch_id INT UNSIGNED NOT NULL,
 target_location_id INT UNSIGNED NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'ALLOCATED',
 idempotency_key CHAR(64) NOT NULL,
 created_by INT UNSIGNED NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX ix_exp_alloc_dn_status(dn_id,status,id),
 INDEX ix_exp_alloc_source(source_manifest_id,status),
 INDEX ix_exp_alloc_target(target_manifest_id,status),
 UNIQUE KEY uq_exp_alloc_request(idempotency_key),
 CONSTRAINT fk_exp_alloc_dn FOREIGN KEY(dn_id) REFERENCES exp_dns(id),
 CONSTRAINT fk_exp_alloc_source FOREIGN KEY(source_manifest_id) REFERENCES exp_manifests(id),
 CONSTRAINT fk_exp_alloc_target FOREIGN KEY(target_manifest_id) REFERENCES exp_manifests(id),
 CONSTRAINT fk_exp_alloc_source_branch FOREIGN KEY(source_branch_id) REFERENCES branches(id),
 CONSTRAINT fk_exp_alloc_source_location FOREIGN KEY(source_location_id) REFERENCES md_locations(id),
 CONSTRAINT fk_exp_alloc_target_branch FOREIGN KEY(target_branch_id) REFERENCES branches(id),
 CONSTRAINT fk_exp_alloc_target_location FOREIGN KEY(target_location_id) REFERENCES md_locations(id),
 CONSTRAINT fk_exp_alloc_actor FOREIGN KEY(created_by) REFERENCES users(id),
 CONSTRAINT ck_exp_alloc_quantity CHECK(quantity>0),
 CONSTRAINT ck_exp_alloc_status CHECK(status IN('ALLOCATED','LOADED','IN_TRANSIT','ARRIVED','RECEIVED','CLOSED'))
) ENGINE=InnoDB;

CREATE TABLE exp_receipt_lines (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 receipt_id INT UNSIGNED NOT NULL,
 allocation_id BIGINT UNSIGNED NOT NULL,
 quantity_received DECIMAL(12,3) NOT NULL,
 quantity_short DECIMAL(12,3) NOT NULL DEFAULT 0,
 quantity_damaged DECIMAL(12,3) NOT NULL DEFAULT 0,
 condition_note VARCHAR(1000) NOT NULL DEFAULT '',
 exception_reason VARCHAR(1000) NULL,
 received_by INT UNSIGNED NOT NULL,
 received_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 idempotency_key CHAR(64) NOT NULL,
 UNIQUE KEY uq_exp_receipt_line_request(idempotency_key),
 UNIQUE KEY uq_exp_receipt_allocation(receipt_id,allocation_id),
 INDEX ix_exp_receipt_line_allocation(allocation_id),
 CONSTRAINT fk_exp_receipt_line_receipt FOREIGN KEY(receipt_id) REFERENCES exp_receipts(id),
 CONSTRAINT fk_exp_receipt_line_allocation FOREIGN KEY(allocation_id) REFERENCES exp_manifest_allocations(id),
 CONSTRAINT fk_exp_receipt_line_actor FOREIGN KEY(received_by) REFERENCES users(id),
 CONSTRAINT ck_exp_receipt_line_received CHECK(quantity_received>0),
 CONSTRAINT ck_exp_receipt_line_short CHECK(quantity_short>=0),
 CONSTRAINT ck_exp_receipt_line_damaged CHECK(quantity_damaged>=0)
) ENGINE=InnoDB;
