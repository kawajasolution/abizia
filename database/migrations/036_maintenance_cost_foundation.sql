CREATE TABLE maintenance_cost_rates (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 branch_id INT UNSIGNED NULL,
 rate_code VARCHAR(60) NOT NULL,
 description VARCHAR(255) NOT NULL,
 rate_per_hour DECIMAL(18,2) NOT NULL,
 effective_from DATE NOT NULL,
 effective_until DATE NULL,
 active TINYINT(1) NOT NULL DEFAULT 1,
 created_by INT UNSIGNED NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NULL,
 UNIQUE KEY uq_mcost_rate_code(rate_code),
 KEY ix_mcost_rate_scope(branch_id,active,effective_from),
 CONSTRAINT fk_mcost_rate_branch FOREIGN KEY(branch_id) REFERENCES branches(id),
 CONSTRAINT fk_mcost_rate_user FOREIGN KEY(created_by) REFERENCES users(id),
 CONSTRAINT ck_mcost_rate_amount CHECK(rate_per_hour>=0)
) ENGINE=InnoDB;
CREATE TABLE maintenance_cost_entries (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 work_order_id BIGINT UNSIGNED NOT NULL,
 branch_id INT UNSIGNED NOT NULL,
 asset_id INT UNSIGNED NOT NULL,
 category ENUM('SPARE_PART','LABOR','EXTERNAL_SERVICE') NOT NULL,
 source_type VARCHAR(40) NOT NULL,
 source_id BIGINT UNSIGNED NULL,
 source_ref VARCHAR(120) NULL,
 description VARCHAR(255) NOT NULL,
 quantity DECIMAL(18,3) NULL,
 unit_cost DECIMAL(18,2) NULL,
 total_cost DECIMAL(18,2) NULL,
 valuation_status ENUM('VALUED','UNVALUED') NOT NULL DEFAULT 'UNVALUED',
 payment_status ENUM('NOT_APPLICABLE','UNPAID','PARTIALLY_PAID','PAID') NOT NULL DEFAULT 'NOT_APPLICABLE',
 created_by INT UNSIGNED NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NULL,
 UNIQUE KEY uq_mcost_source(work_order_id,category,source_type,source_id),
 KEY ix_mcost_wo(work_order_id,category,valuation_status),
 CONSTRAINT fk_mcost_wo FOREIGN KEY(work_order_id) REFERENCES maintenance_work_orders(id),
 CONSTRAINT fk_mcost_branch FOREIGN KEY(branch_id) REFERENCES branches(id),
 CONSTRAINT fk_mcost_asset FOREIGN KEY(asset_id) REFERENCES md_assets(id),
 CONSTRAINT fk_mcost_user FOREIGN KEY(created_by) REFERENCES users(id),
 CONSTRAINT ck_mcost_amount CHECK((quantity IS NULL OR quantity>=0) AND (unit_cost IS NULL OR unit_cost>=0) AND (total_cost IS NULL OR total_cost>=0))
) ENGINE=InnoDB;
CREATE TABLE maintenance_external_services (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 work_order_id BIGINT UNSIGNED NOT NULL,
 branch_id INT UNSIGNED NOT NULL,
 vendor_id INT UNSIGNED NULL,
 service_ref VARCHAR(100) NOT NULL,
 description VARCHAR(255) NOT NULL,
 amount DECIMAL(18,2) NULL,
 service_date DATE NOT NULL,
 status ENUM('RECORDED','APPROVED','PAID') NOT NULL DEFAULT 'RECORDED',
 created_by INT UNSIGNED NOT NULL,
 approved_by INT UNSIGNED NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 approved_at DATETIME NULL,
 UNIQUE KEY uq_mcost_external_ref(branch_id,service_ref),
 KEY ix_mcost_external_wo(work_order_id,status),
 CONSTRAINT fk_mcost_ext_wo FOREIGN KEY(work_order_id) REFERENCES maintenance_work_orders(id),
 CONSTRAINT fk_mcost_ext_branch FOREIGN KEY(branch_id) REFERENCES branches(id),
 CONSTRAINT fk_mcost_ext_user FOREIGN KEY(created_by) REFERENCES users(id),
 CONSTRAINT fk_mcost_ext_approver FOREIGN KEY(approved_by) REFERENCES users(id),
 CONSTRAINT ck_mcost_ext_amount CHECK(amount IS NULL OR amount>=0)
) ENGINE=InnoDB;
